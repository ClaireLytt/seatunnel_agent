"""Contract bootstrap — generate a starting YAML contract from actual DDL.

``seatunnel-agent contract --init`` turns the current state into declared
promises: every table's columns and types become declarations, columns
that already carry a COMMENT get ``comment: true``, and partition keys
land in ``partitioned_by``. The team trims the draft and checks it in;
from then on the contract gate guards against drifting away from it.
"""

from __future__ import annotations

from pathlib import Path


def _column_line(name: str, col_type: str, commented: bool) -> str:
    parts = [f"name: {name}"]
    if col_type:
        # compact + quoted: a comma inside DECIMAL(16,2) must not split
        # the YAML flow mapping
        compact = "".join(col_type.lower().split())
        parts.append(f"type: '{compact}'")
    if commented:
        parts.append("comment: true")
    return "      - { " + ", ".join(parts) + " }"


def generate_contract(sql_text: str, dialect: str = "hive") -> str:
    """DDL text → contract YAML draft (tables sorted, columns in DDL order)."""
    from seatunnel_agent.agents.data.schema_drift.differ import (
        parse_schema_script,
    )

    tables, _ = parse_schema_script(sql_text, dialect)
    if not tables:
        raise ValueError("no CREATE TABLE statements found in the input")
    lines = ["# generated by `seatunnel-agent contract --init` - trim to the",
             "# promises the team actually makes, then check it in",
             "tables:"]
    for name in sorted(tables):
        schema = tables[name]
        lines.append(f"  - name: {name}")
        cols = [c for c in schema.columns.values() if not c.is_partition]
        if cols:
            lines.append("    columns:")
            for c in cols:
                lines.append(_column_line(
                    c.name, c.col_type, bool((c.comment or "").strip())))
        if schema.partition_cols:
            lines.append(
                f"    partitioned_by: [{', '.join(schema.partition_cols)}]")
    return "\n".join(lines) + "\n"


def generate_from_dir(directory: str | Path, dialect: str = "hive") -> str:
    base = Path(directory)
    files = sorted(base.rglob("*.sql"))
    text = "\n;\n".join(p.read_text(encoding="utf-8") for p in files)
    return generate_contract(text, dialect)
